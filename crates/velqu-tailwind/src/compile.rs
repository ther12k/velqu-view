//! The v0 Tailwind-compatible utility synthesizer: utility classes in, CSS
//! text out — the "Tailwind build" stage of the Velqu pipeline
//! (utilities → CSS → profile check → renderer), with no node toolchain and
//! no network.
//!
//! v0 scope is exactly the renderer's profile expressed as utilities:
//! display/flex/grid layout, positioning/inset/z-index, spacing, sizing,
//! the v3 color palette (with `/NN` and `/[0.NN]` opacity modifiers), the
//! `<number>px` arbitrary lengths the reference UI needs, typography,
//! borders/radius, overflow, opacity/scale/translate, and the transition
//! families (`transition-*`, `duration-*`, `ease-*`, `delay-*`, ADR 0024,
//! with the named animations' `@keyframes` emitted alongside). The
//! interaction variants (`hover:`, `focus:`, `active:`) compile to
//! `.class:hover`-style pseudo-class rules restricted to the renderer's
//! paint-only interaction set (ADR 0011); fractional sizes and insets
//! (`w-1/2`, `left-1/2`) resolve to percentages; negative insets
//! (`-top-5`) negate the spacing scale; `cursor-pointer` maps onto the
//! renderer's cursor set; and `border-[#hex]` arbitrary colors emit
//! `border-color`. Everything else — other variants (`focus-visible:`,
//! `disabled:`, `sm:`), non-px arbitrary values (`w-[91%]`),
//! box-shadow utilities (the renderer has no shadow property yet), and
//! utilities outside the renderer profile (`position: sticky`,
//! `pointer-events-*`, `select-none`, `truncate`) — produces a
//! deterministic diagnostic, never a silent drop
//! (docs/tailwind-batch2-notes.md records the renderer-side limits).
//!
//! The output is plain CSS: one rule per class, in first-use order, so the
//! renderer's normal cascade applies (class specificity beats element
//! rules; stylesheets loaded after the generated sheet can still override
//! utilities at equal specificity). Class selectors escape every character
//! outside `[A-Za-z0-9-_]` (`.bg-white\/10`, `.p-2\.5`, `.h-\[48px\]`) so
//! the generated sheet stays parseable while still matching the DOM class
//! attribute text-for-text; a variant rule appends the real pseudo-class
//! (`.hover\:bg-white\/10:hover`), which is exactly the shape the
//! renderer's M4b interaction styling matches.

use crate::{is_interaction_paint_property, palette};

/// One utility class the compiler could not map, with the reason. The
/// renderer never sees the class, so this list is the only place a dropped
/// utility is reported.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UtilityDiagnostic {
    /// The class as written in the markup.
    pub class: String,
    /// Why it was not compiled (and how to fix it, where known).
    pub message: String,
}

/// The result of compiling one document's utility classes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TailwindBuild {
    /// Generated CSS text (one rule per unique class, first-use order).
    pub css: String,
    /// Classes skipped, in first-use order (duplicates are not
    /// re-diagnosed).
    pub diagnostics: Vec<UtilityDiagnostic>,
    /// Number of utility rules in `css`.
    pub rules: usize,
}

/// Compiles Tailwind-compatible utility classes into CSS text.
///
/// ```
/// use velqu_tailwind::compile_utilities;
///
/// let build = compile_utilities(&["flex", "items-center", "gap-4"]);
/// assert!(build.diagnostics.is_empty());
/// assert!(build.css.contains(".flex { display: flex; }"));
/// assert!(build.css.contains("align-items: center"));
/// assert_eq!(build.rules, 3);
/// ```
pub fn compile_utilities(classes: &[&str]) -> TailwindBuild {
    // Preflight-lite: Tailwind sizing assumes border-box everywhere (the
    // universal selector has zero specificity, so any author rule wins).
    let mut css =
        String::from("/* generated by velqu-tailwind v0 */\n* { box-sizing: border-box; }\n");
    let mut diagnostics = Vec::new();
    let mut rules = 0usize;
    let mut seen: Vec<&str> = Vec::new();
    let mut keyframes: Vec<&'static str> = Vec::new();

    for class in classes {
        let class = class.trim();
        if class.is_empty() || seen.contains(&class) {
            continue;
        }
        seen.push(class);
        // The reserved author-hook namespace (M7, ADR 0023): classes
        // prefixed `vv-` are the document's own semantic/test hooks
        // (paired with `data-vv-test`), never utilities. Skipping them
        // is a documented convention, not a disabled check — unknown
        // unprefixed utilities still diagnose.
        if class.starts_with("vv-") {
            continue;
        }
        match compile_one_class(class) {
            Ok((selector, declarations)) => {
                let body = declarations
                    .iter()
                    .map(|(property, value)| format!("{property}: {value};"))
                    .collect::<Vec<_>>()
                    .join(" ");
                css.push_str(&format!(".{selector} {{ {body} }}\n"));
                rules += 1;
                // Tailwind emits the `@keyframes` a named animation needs
                // alongside the utility; mirror that so the build output is
                // self-contained (the renderer drives the presets natively,
                // so this is output completeness, not a runtime dependency).
                if let Some(name) = named_animation(class) {
                    if !keyframes.contains(&name) {
                        keyframes.push(name);
                    }
                }
            }
            Err(message) => diagnostics.push(UtilityDiagnostic {
                class: class.to_owned(),
                message,
            }),
        }
    }

    for name in keyframes {
        let body = ANIMATION_KEYFRAMES
            .iter()
            .find(|(known, _)| *known == name)
            .map(|(_, body)| *body)
            .expect("keyframes name comes from the table");
        css.push_str(&format!("@keyframes {name} {{ {body} }}\n"));
    }

    TailwindBuild {
        css,
        diagnostics,
        rules,
    }
}

/// Escapes a class name for use in a CSS class selector: every character
/// outside `[A-Za-z0-9-_]` gets a backslash (`.bg-white\/10`, `.p-2\.5`,
/// `.h-\[48px\]`). A CSS parser unescapes the identifier, so the rule still
/// matches the DOM class attribute text-for-text.
fn escape_class_selector(class: &str) -> String {
    let mut escaped = String::with_capacity(class.len());
    for c in class.chars() {
        if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
            escaped.push(c);
        } else {
            escaped.push('\\');
            escaped.push(c);
        }
    }
    escaped
}

/// One compiled class: the escaped selector text that follows the leading
/// `.` plus its declarations.
type CompiledClass = (String, Vec<(&'static str, String)>);

/// The interaction variants the renderer's M4b profile matches (ADR 0011,
/// frozen set): Tailwind variant name → emitted pseudo-class. Anything
/// else after the first colon (`focus-visible:`, `disabled:`, `sm:`,
/// `group-hover:`) is diagnosed — the renderer's selector parser skips
/// rules whose pseudo-classes fall outside this set.
const VARIANT_PSEUDO_CLASSES: [(&str, &str); 3] =
    [("hover", "hover"), ("focus", "focus"), ("active", "active")];

/// Compiles one class (bare utility or `variant:utility`) into the escaped
/// selector text that follows the leading `.` plus its declarations.
fn compile_one_class(class: &str) -> Result<CompiledClass, String> {
    match class.split_once(':') {
        Some((variant, inner)) => variant_declarations(class, variant, inner),
        None => utility_declarations(class).map(|d| (escape_class_selector(class), d)),
    }
}

/// Compiles a `hover:bg-white/10`-style variant: the inner utility is
/// compiled to the same declarations as its bare form, then wrapped in the
/// pseudo-class selector the renderer's M4b interaction styling already
/// matches (`.hover\:bg-white\/10:hover`). ADR 0011 keeps interaction
/// rules paint-only — the cascade defers layout properties inside
/// stateful rules with a runtime diagnostic — so a variant whose inner
/// utility touches anything outside the frozen paint set is diagnosed
/// here, at build time, instead.
fn variant_declarations(class: &str, variant: &str, inner: &str) -> Result<CompiledClass, String> {
    let Some(&(_, pseudo)) = VARIANT_PSEUDO_CLASSES
        .iter()
        .find(|(name, _)| *name == variant)
    else {
        return Err(format!(
            "variant {variant}: is outside the renderer's interaction profile \
             (hover:/focus:/active: per ADR 0011); focus-visible:, disabled:, \
             responsive, and group-* variants are not applied in profile v0"
        ));
    };
    if inner.is_empty() {
        return Err(format!(
            "variant {variant}: needs a utility after the colon"
        ));
    }
    let declarations = utility_declarations(inner)?;
    if let Some((property, _)) = declarations
        .iter()
        .find(|(property, _)| !is_interaction_paint_property(property))
    {
        return Err(format!(
            "variant {variant}: may only change paint properties (ADR 0011); \
             {property} under :{pseudo} would be deferred at runtime — put it \
             on the base utility instead"
        ));
    }
    Ok((
        format!("{}:{pseudo}", escape_class_selector(class)),
        declarations,
    ))
}

/// The named `@keyframes` a class needs: `animate-spin` and the
/// variant-wrapped `hover:animate-spin` both carry the spin keyframes.
fn named_animation(class: &str) -> Option<&'static str> {
    let bare = match class.split_once(':') {
        Some((_, inner)) => inner,
        None => class,
    };
    let animation = bare.strip_prefix("animate-")?;
    ANIMATION_KEYFRAMES
        .iter()
        .find(|(known, _)| *known == animation)
        .map(|(name, _)| *name)
}

/// The `@keyframes` the named animation utilities reference (Tailwind v3
/// definitions, verbatim shapes).
const ANIMATION_KEYFRAMES: &[(&str, &str)] = &[
    (
        "spin",
        "from { transform: rotate(0deg); } to { transform: rotate(360deg); }",
    ),
    ("pulse", "0%, 100% { opacity: 1; } 50% { opacity: 0.5; }"),
    (
        "bounce",
        "0%, 100% { transform: translateY(-25%); \
         animation-timing-function: cubic-bezier(0.8, 0, 1, 1); } \
         50% { transform: none; \
         animation-timing-function: cubic-bezier(0, 0, 0.2, 1); }",
    ),
];

/// Why an opacity modifier on a non-color utility is refused, shared by the
/// named-scale and arbitrary-value dispatch paths.
const OPACITY_MODIFIER_ONLY_ON_COLOR: &str = "an opacity modifier only applies \
     to a color utility (bg-<color>/NN, text-<color>/NN, border-<color>/NN)";

/// Characters a class may contain for the v0 pipeline: CSS-escape-free
/// identifiers the renderer's selector parser handles as authored. A `.` is
/// allowed so the decimal spacing steps (`p-2.5`) compile; `compile_utilities`
/// escapes it in the generated selector.
fn is_plain_class(class: &str) -> bool {
    class
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && class
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.')
}

/// Maps one utility class to its declarations, or explains why it is
/// outside the v0 profile.
fn utility_declarations(class: &str) -> Result<Vec<(&'static str, String)>, String> {
    // Structural refusals first, with targeted guidance.
    if class.contains(':') {
        return Err("nested variants (a:b:…) are not applied; one interaction \
                    variant (hover:/focus:/active:) per class"
            .into());
    }
    if class.contains('!') {
        return Err("the !important modifier is not part of profile v0".into());
    }
    // Negative utilities (ADR 0024): a leading dash is a sign, not part of
    // the identifier. `translate-*`, `rotate-*`, and the inset families
    // accept one in profile v0.
    let (negative, class) = match class.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, class),
    };
    if negative
        && !(class.starts_with("translate-")
            || class.starts_with("rotate-")
            || NEGATABLE_INSETS
                .iter()
                .any(|prefix| class.starts_with(prefix)))
    {
        return Err(
            "negative utilities are only supported for translate-*, rotate-*, \
             and inset-* in profile v0"
                .into(),
        );
    }
    // Opacity modifiers (`bg-white/10`, `text-white/[0.06]`) are only
    // meaningful on the color utilities, so a `/` elsewhere is a fraction
    // (`w-1/2`) or a malformed modifier (`bg-white/200`).
    let (class, alpha) = split_alpha_modifier(class);
    // Arbitrary values (`w-[48px]`): the bracketed tail replaces the
    // utility's argument. Malformed brackets keep the deferral diagnostic.
    let (class, arbitrary) = split_arbitrary_value(class)?;
    // Fractional sizes/insets (`w-1/2`, `left-1/2`): a digit/digit tail on
    // a size or inset utility. Anything else keeps its usual diagnostic.
    let (class, fraction) = split_fraction(class);
    if !is_plain_class(class) {
        return Err(format!(
            "class {class:?} needs CSS escaping (fractions or symbols); \
             the v0 pipeline compiles plain [A-Za-z0-9-_.] classes only"
        ));
    }

    // Arbitrary-value utilities dispatch separately: the bracket carries the
    // argument the named scale would provide. A modifier alongside a bracket
    // (`text-[10px]/50`) has nothing to land on, so diagnose — never silent.
    if let Some(value) = arbitrary {
        if alpha.is_some() {
            return Err(OPACITY_MODIFIER_ONLY_ON_COLOR.into());
        }
        let declarations = arbitrary_value_declarations(class, value)?;
        return Ok(declarations);
    }

    // A color utility carrying an opacity modifier resolves here, so the
    // modifier can only ever land on a color: `text-lg/50` and `border-2/50`
    // diagnose instead of silently ignoring the `/50`.
    if let Some(alpha) = alpha {
        return modified_color(class, alpha);
    }

    // A fractional size/inset value resolves to a percentage; other
    // fractions diagnose (deterministically) instead of hitting the
    // generic escaping refusal.
    if let Some(fraction) = fraction {
        return fraction_declarations(class, fraction, negative);
    }

    // Three-level families: the first dash is part of the utility name, so
    // they are handled before the base/argument split.
    if let Some(rest) = class.strip_prefix("justify-items-") {
        return justify_items(rest);
    }
    if let Some(rest) = class.strip_prefix("justify-self-") {
        return justify_self(rest);
    }
    if let Some(rest) = class.strip_prefix("min-w-") {
        return Ok(vec![("min-width", size_value(rest)?)]);
    }
    if let Some(rest) = class.strip_prefix("min-h-") {
        return Ok(vec![("min-height", size_value(rest)?)]);
    }
    if let Some(rest) = class.strip_prefix("max-w-") {
        return Ok(vec![("max-width", max_width(rest)?)]);
    }
    if let Some(rest) = class.strip_prefix("max-h-") {
        return Ok(vec![("max-height", size_value(rest)?)]);
    }
    if let Some(rest) = class.strip_prefix("overflow-x-") {
        return overflow_axis("overflow-x", rest);
    }
    if let Some(rest) = class.strip_prefix("overflow-y-") {
        return overflow_axis("overflow-y", rest);
    }
    if let Some(rest) = class.strip_prefix("translate-x-") {
        return translate_axis('x', rest, negative);
    }
    if let Some(rest) = class.strip_prefix("translate-y-") {
        return translate_axis('y', rest, negative);
    }
    if let Some(rest) = class.strip_prefix("inset-x-") {
        let value = negate_inset(inset_value(rest)?, negative, "inset-x")?;
        return Ok(vec![("left", value.clone()), ("right", value)]);
    }
    if let Some(rest) = class.strip_prefix("inset-y-") {
        let value = negate_inset(inset_value(rest)?, negative, "inset-y")?;
        return Ok(vec![("top", value.clone()), ("bottom", value)]);
    }

    // Renderer-absent property (docs/tailwind-batch2-notes.md): named
    // diagnostic instead of the generic catch-all. The dash-bearing class
    // never reaches the base/arg split as a `pointer-events` family, so it
    // is handled before it.
    if let Some(rest) = class.strip_prefix("pointer-events-") {
        if rest == "none" || rest == "auto" {
            return Err("pointer-events is not applied by the renderer yet (hit \
                 testing owns pointer routing)"
                .into());
        }
        return Err(format!("unknown pointer-events utility {class:?}"));
    }

    let (base, arg) = match class.split_once('-') {
        Some((base, arg)) => (base, Some(arg)),
        None => (class, None),
    };

    match (base, arg) {
        // -- display -----------------------------------------------------
        ("block", None) => Ok(vec![("display", "block".into())]),
        ("inline", None) => Ok(vec![("display", "inline".into())]),
        ("flex", None) => Ok(vec![("display", "flex".into())]),
        ("grid", None) => Ok(vec![("display", "grid".into())]),
        ("hidden", None) => Ok(vec![("display", "none".into())]),
        ("inline-block" | "inline-flex" | "inline-grid" | "table" | "contents", _) => {
            Err("display value outside the renderer profile (block/inline/flex/grid/none)".into())
        }

        // -- flex ------------------------------------------------------------
        ("flex", Some("row")) => Ok(vec![("flex-direction", "row".into())]),
        ("flex", Some("row-reverse")) => Ok(vec![("flex-direction", "row-reverse".into())]),
        ("flex", Some("col")) => Ok(vec![("flex-direction", "column".into())]),
        ("flex", Some("col-reverse")) => Ok(vec![("flex-direction", "column-reverse".into())]),
        ("flex", Some("wrap")) => Ok(vec![("flex-wrap", "wrap".into())]),
        ("flex", Some("wrap-reverse")) => {
            Err("flex-wrap: wrap-reverse is outside the renderer profile".into())
        }
        ("flex", Some("nowrap")) => Ok(vec![("flex-wrap", "nowrap".into())]),
        ("flex", Some("1")) => Ok(vec![
            ("flex-grow", "1".into()),
            ("flex-shrink", "1".into()),
            ("flex-basis", "0%".into()),
        ]),
        ("flex", Some("auto")) => Ok(vec![
            ("flex-grow", "1".into()),
            ("flex-shrink", "1".into()),
            ("flex-basis", "auto".into()),
        ]),
        ("flex", Some("none")) => Ok(vec![
            ("flex-grow", "0".into()),
            ("flex-shrink", "0".into()),
            ("flex-basis", "auto".into()),
        ]),
        ("flex", Some("initial")) => Ok(vec![
            ("flex-grow", "0".into()),
            ("flex-shrink", "1".into()),
            ("flex-basis", "auto".into()),
        ]),
        ("grow", None) => Ok(vec![("flex-grow", "1".into())]),
        ("grow", Some("0")) => Ok(vec![("flex-grow", "0".into())]),
        ("shrink", None) => Ok(vec![("flex-shrink", "1".into())]),
        ("shrink", Some("0")) => Ok(vec![("flex-shrink", "0".into())]),

        // -- alignment ----------------------------------------------------
        ("justify", Some("start" | "normal")) => Ok(vec![("justify-content", "flex-start".into())]),
        ("justify", Some("center")) => Ok(vec![("justify-content", "center".into())]),
        ("justify", Some("end")) => Ok(vec![("justify-content", "flex-end".into())]),
        ("justify", Some("between")) => Ok(vec![("justify-content", "space-between".into())]),
        ("justify", Some(other)) => Err(format!(
            "justify-{other} is outside the renderer profile \
             (start/center/end/between)"
        )),
        ("items", Some("start")) => Ok(vec![("align-items", "flex-start".into())]),
        ("items", Some("center")) => Ok(vec![("align-items", "center".into())]),
        ("items", Some("end")) => Ok(vec![("align-items", "flex-end".into())]),
        ("items", Some("stretch")) => Ok(vec![("align-items", "stretch".into())]),
        // Accepted; the renderer diagnoses the deferral and lays out as
        // flex-start — never silent.
        ("items", Some("baseline")) => Ok(vec![("align-items", "baseline".into())]),
        ("items", Some(other)) => Err(format!("unknown align-items value {other:?}")),
        ("self", Some("auto")) => Ok(vec![("align-self", "auto".into())]),
        ("self", Some("start")) => Ok(vec![("align-self", "flex-start".into())]),
        ("self", Some("center")) => Ok(vec![("align-self", "center".into())]),
        ("self", Some("end")) => Ok(vec![("align-self", "flex-end".into())]),
        ("self", Some("stretch")) => Ok(vec![("align-self", "stretch".into())]),
        ("self", Some(other)) => Err(format!("unknown align-self value {other:?}")),

        // -- grid ----------------------------------------------------------
        // Kept guard-free (no let-chains): the MSRV is 1.87.
        ("grid", Some(kind)) => grid_tracks(kind),
        ("col", Some(kind)) => grid_line("grid-column", kind),
        ("row", Some(kind)) => grid_line("grid-row", kind),

        // -- gap / spacing / sizing ---------------------------------------
        ("gap", Some(axis)) if axis.starts_with("x-") => {
            Ok(vec![("column-gap", spacing_px(&axis[2..], "gap-x")?)])
        }
        ("gap", Some(axis)) if axis.starts_with("y-") => {
            Ok(vec![("row-gap", spacing_px(&axis[2..], "gap-y")?)])
        }
        ("gap", Some(value)) => Ok(vec![("gap", spacing_px(value, "gap")?)]),
        ("p", Some(value)) => Ok(vec![("padding", spacing_px(value, "p")?)]),
        ("px", Some(value)) => Ok(vec![
            ("padding-left", spacing_px(value, "px")?),
            ("padding-right", spacing_px(value, "px")?),
        ]),
        ("py", Some(value)) => Ok(vec![
            ("padding-top", spacing_px(value, "py")?),
            ("padding-bottom", spacing_px(value, "py")?),
        ]),
        ("pt", Some(value)) => Ok(vec![("padding-top", spacing_px(value, "pt")?)]),
        ("pr", Some(value)) => Ok(vec![("padding-right", spacing_px(value, "pr")?)]),
        ("pb", Some(value)) => Ok(vec![("padding-bottom", spacing_px(value, "pb")?)]),
        ("pl", Some(value)) => Ok(vec![("padding-left", spacing_px(value, "pl")?)]),
        ("m", Some(value)) => Ok(vec![("margin", spacing_px(value, "m")?)]),
        ("mx", Some(value)) => Ok(vec![
            ("margin-left", spacing_px(value, "mx")?),
            ("margin-right", spacing_px(value, "mx")?),
        ]),
        ("my", Some(value)) => Ok(vec![
            ("margin-top", spacing_px(value, "my")?),
            ("margin-bottom", spacing_px(value, "my")?),
        ]),
        ("mt", Some(value)) => Ok(vec![("margin-top", spacing_px(value, "mt")?)]),
        ("mr", Some(value)) => Ok(vec![("margin-right", spacing_px(value, "mr")?)]),
        ("mb", Some(value)) => Ok(vec![("margin-bottom", spacing_px(value, "mb")?)]),
        ("ml", Some(value)) => Ok(vec![("margin-left", spacing_px(value, "ml")?)]),
        ("w", Some(value)) => Ok(vec![("width", size_value(value)?)]),
        ("h", Some(value)) => Ok(vec![("height", size_value(value)?)]),

        // -- typography ------------------------------------------------------
        ("text", Some("left" | "center" | "right")) => Ok(vec![(
            "text-align",
            class.rsplit('-').next().expect("non-empty").to_owned(),
        )]),
        ("text", Some(token)) => {
            if let Some((size, leading)) = is_font_size(token) {
                Ok(vec![
                    ("font-size", format!("{size}px")),
                    ("line-height", format!("{leading}px")),
                ])
            } else {
                match color_token(token) {
                    Some(hex) => Ok(vec![("color", hex.to_owned())]),
                    None => Err(format!("unknown text utility {class:?} (size or color?)")),
                }
            }
        }
        ("font", Some(weight)) => match font_weight(weight) {
            Some(value) => Ok(vec![("font-weight", value.to_owned())]),
            None => Err(format!(
                "unknown font utility {class:?} (font families are deferred)"
            )),
        },
        ("leading", Some("none")) => Ok(vec![("line-height", "1".into())]),
        ("leading", Some("tight")) => Ok(vec![("line-height", "1.25".into())]),
        ("leading", Some("snug")) => Ok(vec![("line-height", "1.375".into())]),
        ("leading", Some("normal")) => Ok(vec![("line-height", "1.5".into())]),
        ("leading", Some("relaxed")) => Ok(vec![("line-height", "1.625".into())]),
        ("leading", Some("loose")) => Ok(vec![("line-height", "2".into())]),
        ("tracking", _) => Err("letter-spacing is em-based and deferred in profile v0".into()),
        ("text-decoration", _) => Err("text decoration is outside profile v0".into()),

        // -- borders and radius ----------------------------------------------
        ("border", None) => Ok(default_border(1)),
        ("border", Some(token))
            if !token.is_empty() && token.chars().all(|c| c.is_ascii_digit()) =>
        {
            let width: u32 = token
                .parse()
                .map_err(|_| format!("invalid border width {token:?}"))?;
            Ok(default_border(width))
        }
        ("border", Some("solid")) => Ok(vec![("border-style", "solid".into())]),
        ("border", Some("none")) => Ok(vec![("border-style", "none".into())]),
        ("border", Some("dashed" | "dotted" | "double")) => {
            Err("border-style is outside the renderer profile (solid/none only)".into())
        }
        ("border", Some(color)) => match color_token(color) {
            Some(hex) => Ok(vec![("border-color", hex.to_owned())]),
            None => Err(format!("unknown border utility {class:?}")),
        },
        ("rounded", None) => Ok(vec![("border-radius", "4px".into())]),
        ("rounded", Some("none")) => Ok(vec![("border-radius", "0px".into())]),
        ("rounded", Some("sm")) => Ok(vec![("border-radius", "2px".into())]),
        ("rounded", Some("md")) => Ok(vec![("border-radius", "6px".into())]),
        ("rounded", Some("lg")) => Ok(vec![("border-radius", "8px".into())]),
        ("rounded", Some("xl")) => Ok(vec![("border-radius", "12px".into())]),
        ("rounded", Some("2xl")) => Ok(vec![("border-radius", "16px".into())]),
        ("rounded", Some("3xl")) => Ok(vec![("border-radius", "24px".into())]),
        ("rounded", Some("full")) => Ok(vec![("border-radius", "9999px".into())]),

        // -- overflow / white-space ------------------------------------------
        ("overflow", Some("visible" | "hidden" | "auto" | "scroll")) => Ok(vec![(
            "overflow",
            class.rsplit('-').next().expect("non-empty").to_owned(),
        )]),
        ("whitespace", Some("normal")) => Ok(vec![("white-space", "normal".into())]),
        ("whitespace", Some("nowrap")) => Ok(vec![("white-space", "nowrap".into())]),
        // The renderer collapses pre-line/pre-wrap to preserved-whitespace
        // layout (M2a profile); break-spaces is outside it entirely.
        ("whitespace", Some("pre" | "pre-line" | "pre-wrap")) => Ok(vec![(
            "white-space",
            class.rsplit('-').next().expect("non-empty").to_owned(),
        )]),
        ("whitespace", Some("break-spaces")) => {
            Err("white-space: break-spaces is outside the renderer profile".into())
        }

        // -- background ----------------------------------------------------------
        ("bg", Some(color)) => match color_token(color) {
            Some(hex) => Ok(vec![("background-color", hex.to_owned())]),
            None => Err(format!(
                "unknown bg utility {class:?} (gradients/images are deferred)"
            )),
        },

        // -- opacity / transforms (ADR 0024) ----------------------------------
        ("opacity", Some(step)) => match opacity_step(step) {
            Some(value) => Ok(vec![("opacity", value)]),
            None => Err(format!(
                "unknown opacity step {step:?} (0/5/10/20/25/…/95/100 scale)"
            )),
        },
        ("scale", Some(step)) => match scale_step(step) {
            Some(value) => Ok(vec![("transform", format!("scale({value})"))]),
            None => Err(format!(
                "unknown scale step {step:?} (0/50/75/90/95/100/105/110/125/150)"
            )),
        },

        // -- transitions (ADR 0024) --------------------------------------------
        ("transition", None) => Ok(transition_declarations(
            "color, background-color, border-color, opacity, transform",
        )),
        ("transition", Some("all")) => Ok(transition_declarations("all")),
        ("transition", Some("colors")) => Ok(transition_declarations(
            "color, background-color, border-color",
        )),
        ("transition", Some("opacity")) => Ok(transition_declarations("opacity")),
        ("transition", Some("transform")) => Ok(transition_declarations("transform")),
        ("transition", Some("none")) => Ok(vec![
            ("transition-property", "none".into()),
            ("transition-duration", "0s".into()),
        ]),
        ("transition", Some(other)) => Err(format!(
            "unknown transition utility target {other:?} \
             (all/colors/opacity/transform/none)"
        )),
        ("duration", Some(step)) => match time_step(step) {
            Some(ms) => Ok(vec![("transition-duration", format!("{ms}ms"))]),
            None => Err(format!(
                "unknown duration {step:?} (75/100/150/200/300/500/700/1000 scale)"
            )),
        },
        ("delay", Some(step)) => match time_step(step) {
            Some(ms) => Ok(vec![("transition-delay", format!("{ms}ms"))]),
            None => Err(format!(
                "unknown delay {step:?} (75/100/150/200/300/500/700/1000 scale)"
            )),
        },
        ("ease", Some(kind)) => match easing_value(kind) {
            Some(value) => Ok(vec![("transition-timing-function", value.to_owned())]),
            None => Err(format!(
                "unknown easing {kind:?} (linear/in/out/in-out, Tailwind names)"
            )),
        },

        // -- rotation & origin & animation (ADR 0024) --------------------------
        ("rotate", Some(step)) => match rotate_step(step, negative) {
            Some(value) => Ok(vec![("transform", format!("rotate({value})"))]),
            None => Err(format!(
                "unknown rotate step {step:?} (0/1/2/3/6/12/45/90/180 scale)"
            )),
        },
        ("origin", Some(anchor)) => match origin_value(anchor) {
            Some(value) => Ok(vec![("transform-origin", value.to_owned())]),
            None => Err(format!("unknown origin utility {class:?}")),
        },
        ("animate", Some(name)) => match name {
            "none" => Ok(vec![("animation", "none".into())]),
            "spin" => Ok(vec![("animation", "spin 1s linear infinite".into())]),
            "pulse" => Ok(vec![(
                "animation",
                "pulse 2s cubic-bezier(0.4, 0, 0.6, 1) infinite".into(),
            )]),
            "bounce" => Ok(vec![("animation", "bounce 1s infinite".into())]),
            _ => Err(format!(
                "unknown animation utility {class:?} (spin/pulse/bounce/none)"
            )),
        },

        // -- positioning (renderer profile: relative/absolute/static) ----------
        ("static" | "relative" | "absolute", None) => Ok(vec![("position", class.to_owned())]),
        ("fixed" | "sticky", None) => Err(format!(
            "position: {class} is deferred in profile v0; \
             anchor with a relative/absolute parent instead"
        )),
        ("inset", Some(value)) => {
            let value = negate_inset(inset_value(value)?, negative, "inset")?;
            Ok(vec![
                ("top", value.clone()),
                ("right", value.clone()),
                ("bottom", value.clone()),
                ("left", value),
            ])
        }
        ("top", Some(value)) => Ok(vec![(
            "top",
            negate_inset(inset_value(value)?, negative, "top")?,
        )]),
        ("right", Some(value)) => Ok(vec![(
            "right",
            negate_inset(inset_value(value)?, negative, "right")?,
        )]),
        ("bottom", Some(value)) => Ok(vec![(
            "bottom",
            negate_inset(inset_value(value)?, negative, "bottom")?,
        )]),
        ("left", Some(value)) => Ok(vec![(
            "left",
            negate_inset(inset_value(value)?, negative, "left")?,
        )]),

        // -- stacking ----------------------------------------------------------
        ("z", Some(step)) => match z_index(step) {
            Some(value) => Ok(vec![("z-index", value)]),
            None => Err(format!(
                "unknown z step {step:?} (0/10/20/30/40/50 or auto)"
            )),
        },

        // -- cursor (renderer set: auto/default/pointer/text) ------------------
        ("cursor", Some(name)) => match name {
            "auto" | "default" | "pointer" | "text" => Ok(vec![("cursor", name.to_owned())]),
            "grab" | "grabbing" => Err(format!(
                "cursor: {name} is outside the renderer's cursor set \
                 (auto/default/pointer/text); grab cursors are deferred"
            )),
            _ => Err(format!(
                "unknown cursor utility {class:?} (auto/default/pointer/text)"
            )),
        },

        // -- deliberately unsupported but common -----------------------------------
        // box-shadow: the profile manifest commits to it, but the renderer
        // has no shadow property or painter yet — deferred with a named
        // diagnostic (docs/tailwind-batch2-notes.md records the limits,
        // including the rgba()-to-8-digit-hex plan for when it lands).
        ("shadow" | "ring" | "blur", _) => Err(format!(
            "utility {base:?} needs box-shadow, which the renderer does not \
             apply yet; shadows/rings are deferred"
        )),
        (
            "container" | "underline" | "italic" | "uppercase" | "lowercase" | "capitalize"
            | "sr-only" | "antialiased",
            None,
        ) => Err(format!(
            "utility {class:?} is outside the renderer profile v0 \
             (decorations are deferred)"
        )),
        ("truncate", None) => Err(
            "truncate needs text-overflow: ellipsis, which the renderer does \
             not apply yet; overflow-hidden + whitespace-nowrap clip without \
             the ellipsis"
                .into(),
        ),
        ("tabular", Some("nums")) => {
            Err("font-variant-numeric is not applied by the renderer yet; \
             tabular-nums is deferred"
                .into())
        }
        ("select", Some("none")) => Err(
            "user-select is not applied by the renderer yet; select-none is \
             deferred"
                .into(),
        ),
        ("outline", Some("none")) => {
            Err("outline properties are not applied by the renderer yet; \
             outline-none is deferred"
                .into())
        }
        (
            "aspect" | "columns" | "list" | "object" | "align" | "select" | "appearance" | "order"
            | "basis" | "place" | "content" | "outline" | "accent" | "divide" | "space" | "skew"
            | "fill" | "stroke",
            _,
        ) => Err(format!("utility family {base:?} is outside profile v0")),

        _ => Err(format!(
            "class {class:?} is not a known utility in profile v0 \
             (custom CSS still works through stylesheets)"
        )),
    }
}

/// Splits a trailing opacity modifier off a color utility class:
/// `bg-white/10` → (`bg-white`, Some(26)). Only a syntactically valid
/// modifier is taken; anything else (`bg-white/x`, `left-1/2`) is left in
/// place so the class reaches its usual diagnostic.
fn split_alpha_modifier(class: &str) -> (&str, Option<u8>) {
    let color_utility =
        class.starts_with("bg-") || class.starts_with("text-") || class.starts_with("border-");
    if !color_utility {
        return (class, None);
    }
    match class.split_once('/') {
        Some((base, modifier)) => match parse_alpha_channel(modifier) {
            Some(alpha) => (base, Some(alpha)),
            None => (class, None),
        },
        None => (class, None),
    }
}

/// Parses an opacity modifier into the 0–255 alpha channel: `NN` percent
/// (0–100, exact integer math so `/90` composes to 230, not a `0.9f32`
/// wobble) or `[0.NN]` alpha (0.0–1.0), as in `bg-white/25` and
/// `bg-white/[0.06]`.
fn parse_alpha_channel(modifier: &str) -> Option<u8> {
    if let Some(inner) = modifier.strip_prefix('[').and_then(|m| m.strip_suffix(']')) {
        let alpha: f64 = inner.parse().ok()?;
        return (0.0..=1.0)
            .contains(&alpha)
            .then(|| (alpha * 255.0).round() as u8);
    }
    let percent: u16 = modifier.parse().ok()?;
    if !(0..=100).contains(&percent) {
        return None;
    }
    Some(((percent as u32 * 255 + 50) / 100) as u8)
}

/// Splits a bracketed arbitrary value off a utility class: `w-[48px]` →
/// (`w`, Some("48px")). The value is the text between the brackets; the
/// utility keeps everything before the opening bracket's dash.
fn split_arbitrary_value(class: &str) -> Result<(&str, Option<&str>), String> {
    match class.split_once('[') {
        Some((base, rest)) => {
            let value = rest.strip_suffix(']').filter(|inner| !inner.contains('['));
            match value {
                Some(value) => Ok((base.strip_suffix('-').unwrap_or(base), Some(value))),
                // Malformed brackets (`bg-[`, `shadow-[0`) keep the deferral
                // diagnostic — same contract as profile v0's original refusal.
                None => Err(
                    "arbitrary values (e.g. w-[91px]) are deferred in profile v0; \
                     use the named scale"
                        .into(),
                ),
            }
        }
        None => Ok((class, None)),
    }
}

/// Splits a fractional tail off a size or inset utility: `w-1/2` →
/// (`w`, Some("1/2")). Only a plain `digits/digits` tail splits; anything
/// else (`w-1/x`, `bg-white/200` malformed modifiers) stays whole so the
/// class reaches its usual diagnostic.
fn split_fraction(class: &str) -> (&str, Option<&str>) {
    let Some((left, den)) = class.split_once('/') else {
        return (class, None);
    };
    let den_is_digits = !den.is_empty() && den.chars().all(|c| c.is_ascii_digit());
    let (num_digits_len, num_is_digits) = match left.rsplit_once('-') {
        Some((_, num)) => (
            num.len(),
            !num.is_empty() && num.chars().all(|c| c.is_ascii_digit()),
        ),
        None => (0, false),
    };
    if !num_is_digits || !den_is_digits {
        return (class, None);
    }
    let base = &left[..left.len() - num_digits_len - 1];
    if base.is_empty() {
        return (class, None);
    }
    (base, Some(&class[base.len() + 1..]))
}

/// The inset utility prefixes that accept a leading `-` (`-top-5`,
/// `-left-4`). `inset-x-*`/`inset-y-*` start with `inset-`, so one entry
/// covers them.
const NEGATABLE_INSETS: [&str; 5] = ["top-", "right-", "bottom-", "left-", "inset-"];

/// Negates a spacing-scale inset length for the negative inset utilities
/// (`-top-5` → -20px). `auto`/`full` have no negative form and diagnose.
fn negate_inset(value: String, negative: bool, utility: &str) -> Result<String, String> {
    if !negative {
        return Ok(value);
    }
    if value.ends_with("px") && !value.starts_with('-') {
        Ok(format!("-{value}"))
    } else {
        Err(format!(
            "cannot negate {utility} value {value:?} (only spacing-scale \
             lengths have negative forms)"
        ))
    }
}

/// Fractional size/inset values (`w-1/2`, `left-1/2`): resolved to a
/// percentage of the containing block at layout time (the same contract as
/// `h-full`), which the renderer's length parser accepts. Other fractions
/// diagnose — the compiler never emits a value the renderer would reject.
fn fraction_declarations(
    base: &str,
    fraction: &str,
    negative: bool,
) -> Result<Vec<(&'static str, String)>, String> {
    let pct = fraction_percent(fraction)?;
    let sign = if negative { "-" } else { "" };
    let value = format!("{sign}{pct}%");
    match base {
        "w" => Ok(vec![("width", value)]),
        "h" => Ok(vec![("height", value)]),
        "inset" => Ok(vec![
            ("top", value.clone()),
            ("right", value.clone()),
            ("bottom", value.clone()),
            ("left", value),
        ]),
        "inset-x" => Ok(vec![("left", value.clone()), ("right", value)]),
        "inset-y" => Ok(vec![("top", value.clone()), ("bottom", value)]),
        "top" => Ok(vec![("top", value)]),
        "right" => Ok(vec![("right", value)]),
        "bottom" => Ok(vec![("bottom", value)]),
        "left" => Ok(vec![("left", value)]),
        _ => Err(format!(
            "fractional values ({fraction}) are only supported on the size \
             (w/h) and inset utilities in profile v0"
        )),
    }
}

/// `1/2` → `50`, `2/3` → `66.666667` (Tailwind's 6-decimal percentages,
/// trailing zeros trimmed so `1/2` is `50`, not `50.000000`).
fn fraction_percent(fraction: &str) -> Result<String, String> {
    let (num, den) = fraction
        .split_once('/')
        .expect("fraction shape checked by split_fraction");
    let num: u32 = num
        .parse()
        .map_err(|_| format!("fraction numerator {num:?} must be a non-negative integer"))?;
    let den: u32 = den
        .parse()
        .map_err(|_| format!("fraction denominator {den:?} must be a positive integer"))?;
    if den == 0 {
        return Err(format!(
            "fraction {fraction:?} must have a denominator greater than 0"
        ));
    }
    let mut text = format!("{:.6}", num as f64 * 100.0 / den as f64);
    if text.contains('.') {
        while text.ends_with('0') {
            text.pop();
        }
        if text.ends_with('.') {
            text.pop();
        }
    }
    Ok(text)
}

/// A `#RGB`/`#RRGGBB`/`#RRGGBBAA` literal the renderer's color parser
/// accepts, returned verbatim.
fn hex_color_literal(value: &str) -> Option<&str> {
    let hex = value.strip_prefix('#')?;
    let len = hex.len();
    let digits = (len == 3 || len == 6 || len == 8) && hex.chars().all(|c| c.is_ascii_hexdigit());
    digits.then_some(value)
}

/// Arbitrary `<number>px` lengths for the utilities the reference UI needs
/// (`w-[3px]`, `gap-[2.5px]`, `rounded-[26px]`, `text-[12px]`,
/// `transition-[width]`). Everything else keeps the deferral diagnostic.
fn arbitrary_value_declarations(
    base: &str,
    value: &str,
) -> Result<Vec<(&'static str, String)>, String> {
    // `transition-[…]` carries property names, not a length.
    if base == "transition" {
        if !value.is_empty()
            && value.split(',').all(|property| {
                !property.is_empty() && property.chars().all(|c| c.is_ascii_lowercase() || c == '-')
            })
        {
            return Ok(transition_declarations(value));
        }
        return Err(format!(
            "arbitrary transition property {value:?} must be a comma-separated \
             list of lowercase CSS property names"
        ));
    }
    // `shadow-[…]`/`ring-[…]` need box-shadow, which the renderer has no
    // property or painter for yet — the same named deferral as the
    // named-scale forms (`shadow-md`).
    if matches!(base, "shadow" | "ring" | "blur") {
        return Err(format!(
            "utility {base:?} needs box-shadow, which the renderer does not \
             apply yet; shadows/rings are deferred"
        ));
    }
    // Family first, so an unsupported family (`bg-[#14121f]`) keeps the
    // deferral diagnostic regardless of its value grammar.
    if !matches!(
        base,
        "w" | "h"
            | "min-w"
            | "min-h"
            | "max-w"
            | "max-h"
            | "gap"
            | "gap-x"
            | "gap-y"
            | "p"
            | "px"
            | "py"
            | "pt"
            | "pr"
            | "pb"
            | "pl"
            | "m"
            | "mx"
            | "my"
            | "mt"
            | "mr"
            | "mb"
            | "ml"
            | "inset"
            | "inset-x"
            | "inset-y"
            | "top"
            | "right"
            | "bottom"
            | "left"
            | "rounded"
            | "border"
            | "text"
    ) {
        return Err(format!(
            "arbitrary {base:?} values are deferred in profile v0; \
             use the named scale"
        ));
    }
    // `border-[3px]` carries the named scale's width+style+color triple;
    // `border-[#hex]` colors only (`focus:border-[#2b2540]` is how the
    // reference UI draws its focused border). The hex literal is emitted
    // verbatim — the renderer's color parser accepts 3/6/8-digit hex.
    if base == "border" {
        if let Some(color) = hex_color_literal(value) {
            return Ok(vec![("border-color", color.to_owned())]);
        }
        return Ok(default_border(px_value(value)?));
    }
    let px = arbitrary_px(value)?;
    Ok(match base {
        "w" => vec![("width", px)],
        "h" => vec![("height", px)],
        "min-w" => vec![("min-width", px)],
        "min-h" => vec![("min-height", px)],
        "max-w" => vec![("max-width", px)],
        "max-h" => vec![("max-height", px)],
        "gap" => vec![("gap", px)],
        "gap-x" => vec![("column-gap", px)],
        "gap-y" => vec![("row-gap", px)],
        "p" => vec![("padding", px)],
        "px" => vec![("padding-left", px.clone()), ("padding-right", px)],
        "py" => vec![("padding-top", px.clone()), ("padding-bottom", px)],
        "pt" => vec![("padding-top", px)],
        "pr" => vec![("padding-right", px)],
        "pb" => vec![("padding-bottom", px)],
        "pl" => vec![("padding-left", px)],
        "m" => vec![("margin", px)],
        "mx" => vec![("margin-left", px.clone()), ("margin-right", px)],
        "my" => vec![("margin-top", px.clone()), ("margin-bottom", px)],
        "mt" => vec![("margin-top", px)],
        "mr" => vec![("margin-right", px)],
        "mb" => vec![("margin-bottom", px)],
        "ml" => vec![("margin-left", px)],
        "inset" => vec![
            ("top", px.clone()),
            ("right", px.clone()),
            ("bottom", px.clone()),
            ("left", px),
        ],
        "inset-x" => vec![("left", px.clone()), ("right", px)],
        "inset-y" => vec![("top", px.clone()), ("bottom", px)],
        "top" => vec![("top", px)],
        "right" => vec![("right", px)],
        "bottom" => vec![("bottom", px)],
        "left" => vec![("left", px)],
        "rounded" => vec![("border-radius", px)],
        // Tailwind emits font-size only for an arbitrary size (the named
        // scale owns the line-height pairing).
        "text" => vec![("font-size", px)],
        _ => unreachable!("family membership checked above"),
    })
}

/// Validates an arbitrary length: `<number>px` (0..=4096; fractions like
/// `2.5px` allowed — the renderer's lengths are f32). The number is
/// re-emitted so `w-[03px]` normalizes to `3px`.
fn arbitrary_px(value: &str) -> Result<String, String> {
    let number: f32 = value
        .strip_suffix("px")
        .and_then(|number| number.parse().ok())
        .ok_or_else(|| {
            format!("arbitrary value {value:?} outside the v0 grammar (only <number>px lengths)")
        })?;
    if !(0.0..=4096.0).contains(&number) {
        return Err(format!(
            "arbitrary value {value:?} outside the v0 range (0..=4096px)"
        ));
    }
    Ok(format!("{number}px"))
}

/// Parses an arbitrary `<number>px` width for `border-[Npx]` (integral px,
/// matching the named `border-N` scale that carries width + style + color).
fn px_value(value: &str) -> Result<u32, String> {
    let number: f32 = value
        .strip_suffix("px")
        .and_then(|number| number.parse().ok())
        .ok_or_else(|| {
            format!("arbitrary border width {value:?} outside the v0 grammar (only <number>px)")
        })?;
    if !(0.0..=4096.0).contains(&number) || number.fract() != 0.0 {
        return Err(format!(
            "arbitrary border width {value:?} must be an integral px width (0..=4096)"
        ));
    }
    Ok(number as u32)
}

/// Resolves a color utility that carries an opacity modifier
/// (`bg-white/10` → `background-color: #ffffff1a`). Dispatched before the
/// named-scale match so the modifier can only ever land on a color: a
/// modifier on a non-color utility (`text-lg/50`, `border-2/50`) is a usage
/// error, never a silently ignored `/50`.
fn modified_color(class: &str, alpha: u8) -> Result<Vec<(&'static str, String)>, String> {
    let only_color = || Err(OPACITY_MODIFIER_ONLY_ON_COLOR.into());
    let Some((base, token)) = class.split_once('-') else {
        // An arbitrary size with a modifier (`text-[10px]/50`): the size
        // branch would never carry the alpha, so diagnose.
        return only_color();
    };
    let non_color = match base {
        "text" => is_font_size(token).is_some() || matches!(token, "left" | "center" | "right"),
        "border" => !token.is_empty() && token.chars().all(|c| c.is_ascii_digit()),
        _ => false,
    };
    if non_color {
        return only_color();
    }
    let unknown = match base {
        "bg" => format!("unknown bg utility {class:?} (gradients/images are deferred)"),
        "border" => format!("unknown border utility {class:?}"),
        _ => format!("unknown text utility {class:?} (size or color?)"),
    };
    let hex = color_token(token).ok_or(unknown)?;
    let property = match base {
        "bg" => "background-color",
        "border" => "border-color",
        _ => "color",
    };
    Ok(vec![(property, compose_alpha(hex, alpha))])
}

/// Composes an alpha channel (0–255) into a 6-digit hex color, producing
/// the `#RRGGBBAA` form the renderer's color parser accepts.
fn compose_alpha(hex: &str, alpha: u8) -> String {
    let hex = hex.strip_prefix('#').unwrap_or(hex);
    let channel = |lo: usize| u8::from_str_radix(&hex[lo..lo + 2], 16).unwrap_or(0);
    format!(
        "#{:02x}{:02x}{:02x}{:02x}",
        channel(0),
        channel(2),
        channel(4),
        alpha
    )
}

/// `inset-*`/`top-*`/… values: the spacing scale plus `auto`/`full`
/// (percentage-of-containing-block resolves at layout time, like `h-full`).
fn inset_value(token: &str) -> Result<String, String> {
    match token {
        "auto" => Ok("auto".into()),
        "full" => Ok("100%".into()),
        _ => spacing_px(token, "inset"),
    }
}

/// The `z-<step>` stacking scale (Tailwind v3) + `auto`.
fn z_index(token: &str) -> Option<String> {
    match token {
        "auto" => Some("auto".into()),
        _ => {
            const STEPS: [u16; 6] = [0, 10, 20, 30, 40, 50];
            let step: u16 = token.parse().ok()?;
            STEPS.contains(&step).then(|| step.to_string())
        }
    }
}

/// `grid-cols-N`, `grid-rows-N`, and auto-flow classes.
fn grid_tracks(kind: &str) -> Result<Vec<(&'static str, String)>, String> {
    if let Some(count) = kind.strip_prefix("cols-") {
        let count = track_count(count)?;
        return Ok(vec![(
            "grid-template-columns",
            format!("repeat({count}, minmax(0, 1fr))"),
        )]);
    }
    if let Some(count) = kind.strip_prefix("rows-") {
        let count = track_count(count)?;
        return Ok(vec![(
            "grid-template-rows",
            format!("repeat({count}, minmax(0, 1fr))"),
        )]);
    }
    match kind {
        "flow-row" => Ok(vec![("grid-auto-flow", "row".into())]),
        "flow-col" => Ok(vec![("grid-auto-flow", "column".into())]),
        "flow-dense" | "flow-row-dense" | "flow-col-dense" => {
            Err("dense auto-placement is outside the renderer grid profile".into())
        }
        _ => Err(format!("unknown grid utility {kind:?}")),
    }
}

/// `col-span-N` / `col-start-N` / `col-end-N` and the row equivalents.
fn grid_line(property: &'static str, kind: &str) -> Result<Vec<(&'static str, String)>, String> {
    if let Some(count) = kind.strip_prefix("span-") {
        let count = track_count(count)?;
        return Ok(vec![(property, format!("span {count}"))]);
    }
    if let Some(line) = kind.strip_prefix("start-") {
        let line = track_count(line)?;
        return Ok(vec![(property, format!("{line} / auto"))]);
    }
    if let Some(line) = kind.strip_prefix("end-") {
        let line = track_count(line)?;
        return Ok(vec![(property, format!("auto / {line}"))]);
    }
    Err(format!("unknown {property} utility {kind:?}"))
}

